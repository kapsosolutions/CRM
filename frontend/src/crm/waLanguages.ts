const LABEL = new Map(LIST);

/** The ones most businesses here pick, shown first. */
const PINNED = ['en_US', 'en', 'en_GB', 'en_IN', 'hi', 'te', 'ta', 'kn', 'ml', 'mr', 'gu', 'bn', 'pa', 'ur'];

/** Every template language, for a (searchable) Dropdown: common first, then A–Z. */
export const WA_TEMPLATE_LANGUAGES: KOption[] = [
  ...PINNED.map((v) => ({ value: v, label: LABEL.get(v) as string })),
  ...LIST.filter(([v]) => !PINNED.includes(v)).map(([value, label]) => ({ value, label })),
];

/** "Hindi", "Portuguese (Brazil)"; an unknown code is shown as it is. */
export const waLanguageLabel = (code?: string | null) => (code ? LABEL.get(code) || code : '—');
