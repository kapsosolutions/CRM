// Builds src/crm/emojiData.ts, the emoji list for the chat's emoji picker
// (components/FastEmojiPicker.tsx), from @emoji-mart/data (Unicode 15).
//
//   node frontend/build/make-emoji-data.mjs
//
// One compact string per category instead of the 430 KB JSON: each line is
//   native \t version \t search words \t skin-tone variants (space-separated)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const data = require('@emoji-mart/data/sets/15/native.json');

const NAMES = {
  people: 'Smileys & People',
  nature: 'Animals & Nature',
  foods: 'Food & Drink',
  activity: 'Activity',
  places: 'Travel & Places',
  objects: 'Objects',
  symbols: 'Symbols',
  flags: 'Flags',
};

const words = (e) => {
  const out = new Set();
  const add = (s) => String(s || '').toLowerCase().split(/[\s_\-:,]+/).forEach((w) => w && out.add(w));
  add(e.id);
  add(e.name);
  (e.keywords || []).forEach(add);
  (e.emoticons || []).forEach((x) => out.add(x.toLowerCase()));
  return [...out].join(' ');
};

const categories = data.categories.map((c) => ({
  id: c.id,
  name: NAMES[c.id] || c.id,
  list: c.emojis
    .map((id) => data.emojis[id])
    .filter(Boolean)
    .map((e) => [e.skins[0].native, e.version, words(e), e.skins.slice(1).map((s) => s.native).join(' ')].join('\t'))
    .join('\n'),
}));

const ids = {};
for (const e of Object.values(data.emojis)) ids[e.id] = e.skins[0].native;

const src = `// GENERATED by build/make-emoji-data.mjs from @emoji-mart/data. Do not edit.
// Per line: native \\t Unicode emoji version \\t search words \\t skin-tone variants.
export const EMOJI_CATEGORIES: { id: string; name: string; list: string }[] = ${JSON.stringify(categories, null, 1)};

/** emoji-mart ids -> emoji, to carry over the old picker's "frequently used". */
export const EMOJI_BY_ID: Record<string, string> = ${JSON.stringify(ids)};
`;
const out = join(HERE, '..', 'src', 'crm', 'emojiData.ts');
writeFileSync(out, src);
console.log(`${out}: ${categories.reduce((n, c) => n + c.list.split('\n').length, 0)} emoji, ${(src.length / 1024).toFixed(0)} KB`);
